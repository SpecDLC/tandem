// Projector: ledger/events.jsonl -> public cards, specification, connections, requirements.
// usage: node tools/project.mjs --out DIR     write the projection into DIR
//        node tools/project.mjs --check DIR   exit 1 if DIR differs from the projection (TANDEM-TECH-PROJ-1)
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";

export function readLedger(path) {
  return readFileSync(path, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
}

export function project(events) {
  const spec = events.find((e) => e.type === "com.specdlc.specification.opened.v1");
  if (!spec) throw new Error("ledger has no specification event");
  const acs = events.filter((e) => e.type === "com.specdlc.ac.created.v1");
  const cards = acs.filter((e) => e.data.kind === "card");
  const reqs = acs.filter((e) => e.data.kind !== "card");
  const cardAliases = new Set(cards.map((e) => e.data.alias));
  for (const m of spec.data.members) if (!cardAliases.has(m)) throw new Error(`member ${m} has no ac.created event`);
  const files = {};

  for (const e of cards) {
    const d = e.data;
    files[`cards/${d.alias}.md`] = [
      `# ${d.alias}`, "",
      `Member of [${spec.data.alias}](../spec/SPECIFICATION.md). Projected from ledger event \`${e.id}\`. Do not edit this file; the ledger is the authority.`, "",
      `**Claim.** ${d.claim}`, "",
      `**Interface.** ${d.interface}`, "",
      `**Forbids.** ${d.forbids}`, "",
      `**Binds.** ${d.binds}`, "",
    ].join("\n");
  }

  const s = spec.data;
  files["spec/SPECIFICATION.md"] = [
    `# ${s.alias}`, "",
    `Projected from ledger event \`${spec.id}\`. Do not edit this file; the ledger is the authority.`, "",
    `- **Intent.** ${s.intent}`,
    `- **Entry.** \`${s.entry}\`. The cards are the contract. A reference build comes after.`,
    `- **Delivered when.** ${s.delivered_when}`, "",
    "## Members", "",
    ...s.members.map((m) => `- [${m}](../cards/${m}.md)`), "",
    "See also: [connections](../projections/connections.md), [requirements](../projections/requirements.md).", "",
  ].join("\n");

  const conns = [...cards, ...reqs].flatMap((e) => (e.data.connections ?? []).map((c) => [e.data.alias, c.type, c.to]));
  files["projections/connections.md"] = [
    "# Connections", "",
    "Projected from the `connections` field of each ledger event. Do not edit this file.", "",
    "| From | Type | To |", "|---|---|---|",
    ...conns.map(([a, t, b]) => `| ${a} | ${t} | ${b} |`), "",
  ].join("\n");

  files["projections/requirements.md"] = [
    "# Requirements", "",
    "Projected from the ledger. A binding is inert when its predicate is false. Do not edit this file.", "",
    "| Alias | Kind | Predicate | Refines | Requirement |", "|---|---|---|---|---|",
    ...reqs.map((e) => {
      const d = e.data;
      const r = (d.connections ?? []).map((c) => c.to).join(", ") || "none";
      return `| ${d.alias} | ${d.kind} | ${d.predicate} | ${r} | ${d.text.replace(/\|/g, "\\|")} |`;
    }), "",
  ].join("\n");
  return files;
}

function walk(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(join(dir, d.name), base) : [join(dir, d.name).slice(base.length + 1)]);
}

const [, , mode, dir] = process.argv;
if (mode === "--out" || mode === "--check") {
  const files = project(readLedger(new URL("../ledger/events.jsonl", import.meta.url)));
  if (mode === "--out") {
    for (const [p, body] of Object.entries(files)) { mkdirSync(dirname(join(dir, p)), { recursive: true }); writeFileSync(join(dir, p), body); }
    console.log(`wrote ${Object.keys(files).length} files`);
  } else {
    const bad = [];
    for (const [p, body] of Object.entries(files)) {
      const f = join(dir, p);
      if (!existsSync(f)) bad.push(`missing: ${p}`);
      else if (readFileSync(f, "utf8") !== body) bad.push(`differs: ${p}`);
    }
    for (const p of walk(join(dir, "cards"), dir)) if (!(p in files)) bad.push(`extra: ${p}`);
    if (bad.length) { console.error("public projection drift:\n" + bad.join("\n")); process.exit(1); }
    console.log(`projection matches (${Object.keys(files).length} files)`);
  }
}
